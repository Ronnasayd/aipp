#!/usr/bin/python3
"""Go Lint Hook.

Runs go vet, golangci-lint (if installed) and gofmt checks on Go files after edit.
- Skips if go toolchain not installed
- golangci-lint is optional (falls back to no-op when unavailable)
- Reports vet errors, lint issues and formatting diffs

Cross-platform (Windows, macOS, Linux).
"""

import os
from pathlib import Path
import subprocess
import sys
from typing import Any

script_dir = os.path.dirname(os.path.abspath(__file__))
if script_dir not in sys.path:
    sys.path.append(script_dir)

from utils import (  # noqa: E402
    find_project_root,
    get_hooks_logger,
    parse_json_output,
    run_command_cwd,
    run_jscpd,
    run_lint_hook_main,
    truncate_large_output,
)

logger = get_hooks_logger("GolangLint")

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

_GO_EXTS = {".go"}
_BINDATA_MARKER = "// Code generated by go-bindata."


def _is_generated(path: Path) -> bool:
    """True when the file header marks it as go-bindata output."""
    # why: go-bindata emits the marker as the first line; generated code is
    # not hand-fixable, so linting it only yields noise.
    try:
        with path.open(encoding="utf-8", errors="replace") as fh:
            return fh.readline().startswith(_BINDATA_MARKER)
    except OSError:
        return False


def _exec(bin_: str, args: list[str], cwd: str | None = None) -> dict:
    """Wrapper for tool invocations."""
    cmd = " ".join([bin_, *args])
    return run_command_cwd(cmd, cwd=cwd)


def _check_tool_installed(tool: str) -> bool:
    """Check if tool is installed via system PATH."""
    result = subprocess.run(  # noqa: S603 -- args are fixed literals, not untrusted input
        ["which", tool],  # noqa: S607 -- fixed lookup binary, trusted internal tool name
        capture_output=True,
        timeout=5,
        check=False,
    )
    return result.returncode == 0


def _run_govet(resolved: Path, project_root: str) -> dict:
    """Run go vet. Returns {success, output, error}."""
    if not _check_tool_installed("go"):
        logger.debug("go not installed, skipping vet for %s", resolved)
        return {"success": True, "output": "", "error": "", "installed": False}

    cmd = f"go vet {resolved!s}"
    logger.debug("Executing: %s (cwd=%s)", cmd, project_root)
    result = _exec("go", ["vet", str(resolved)], cwd=project_root)
    logger.debug("go vet result: success=%s", result["success"])
    if result["success"]:
        logger.debug("go vet passed for %s", resolved)
    else:
        logger.warning(
            "go vet found issues in %s:\n%s",
            resolved,
            result.get("output", ""),
        )
    if result.get("error"):
        logger.warning("go vet stderr: %s", result.get("error", ""))
    output = truncate_large_output(result.get("output", ""), "govet")
    return {
        "success": result["success"],
        "output": output,
        "error": result.get("error", ""),
        "installed": True,
    }


def _run_golangci_lint(resolved: Path, project_root: str) -> dict:
    """Run golangci-lint. Returns {success, output, error}.

    `output` is parsed from golangci-lint's `--out-format json` (structured
    Issues list) since agents parse structured data far more reliably than
    the default text output.
    """
    if not _check_tool_installed("golangci-lint"):
        logger.debug("golangci-lint not installed, skipping lint for %s", resolved)
        return {"success": True, "output": "", "error": "", "installed": False}

    cmd = f"golangci-lint run --output.json.path stdout {resolved!s}"
    logger.debug("Executing: %s (cwd=%s)", cmd, project_root)
    result = _exec(
        "golangci-lint",
        ["run", "--output.json.path", "stdout", str(resolved)],
        cwd=project_root,
    )
    logger.debug("golangci-lint result: success=%s", result["success"])
    output = parse_json_output(
        result.get("output", ""), "GolangLint", "golangci-lint", logger
    )
    if result["success"]:
        logger.debug("golangci-lint passed for %s", resolved)
    else:
        logger.warning("golangci-lint found issues in %s:\n%s", resolved, output)
    if result.get("error"):
        logger.warning("golangci-lint stderr: %s", result.get("error", ""))
    output = truncate_large_output(output, "golangci-lint")
    return {
        "success": result["success"],
        "output": output,
        "error": result.get("error", ""),
        "installed": True,
    }


def _run_gofmt(resolved: Path, project_root: str) -> dict:
    """Run gofmt -l to detect formatting diffs. Returns {success, output, error}."""
    if not _check_tool_installed("gofmt"):
        logger.debug("gofmt not installed, skipping fmt check for %s", resolved)
        return {"success": True, "output": "", "error": "", "installed": False}

    cmd = f"gofmt -l {resolved!s}"
    logger.debug("Executing: %s (cwd=%s)", cmd, project_root)
    result = _exec("gofmt", ["-l", str(resolved)], cwd=project_root)
    # why: gofmt -l exits 0 even when files need formatting;
    # non-empty output means unformatted.
    unformatted = bool(result.get("output", "").strip())
    if unformatted:
        logger.warning("gofmt found unformatted file: %s", resolved)
    output = truncate_large_output(result.get("output", ""), "gofmt")
    return {
        "success": result["success"] and not unformatted,
        "output": output,
        "error": result.get("error", ""),
        "installed": True,
    }


def maybe_run_golang_lint(file_path: str | None) -> dict[str, dict[str, Any] | None]:
    """Run go vet, golangci-lint, gofmt and jscpd checks for Go files.

    Args:
        file_path: Path to the edited file.

    Returns:
        Dict with govet, golangci_lint, gofmt and jscpd results.
    """
    result: dict[str, dict[str, Any] | None] = {
        "govet": None,
        "golangci_lint": None,
        "gofmt": None,
        "jscpd": None,
    }

    if not file_path:
        logger.debug("No file_path provided, skipping.")
        return result

    resolved = Path(file_path).resolve()
    if not resolved.exists():
        logger.debug("File %s does not exist, skipping.", resolved)
        return result

    ext = resolved.suffix.lower()
    if ext not in _GO_EXTS:
        logger.debug("File %s not Go, skipping (%s).", resolved, ext)
        return result

    if _is_generated(resolved):
        logger.debug("File %s is generated (go-bindata), skipping.", resolved)
        return result

    project_root = find_project_root(str(resolved.parent))
    logger.debug("Project root for %s: %s", resolved, project_root)

    result["govet"] = _run_govet(resolved, project_root)
    result["golangci_lint"] = _run_golangci_lint(resolved, project_root)
    result["gofmt"] = _run_gofmt(resolved, project_root)
    result["jscpd"] = run_jscpd(resolved, project_root, logger, "GolangLint")
    return result


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def main() -> None:
    """Entry point for the Go lint hook."""
    run_lint_hook_main("GolangLint", logger, maybe_run_golang_lint)


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:  # pylint: disable=broad-exception-caught
        logger.debug("Error: %s", exc)
        sys.exit(0)
