#!/usr/bin/env python3
"""pre-commit: block newly added comments without a declared reason.

Ported from legacy/hooks/comment_policy_hint.py (dead PostToolUse hook) —
same tree-sitter comment scan + why:/hazard:/invariant: marker judgement,
but driven off staged git content instead of a Claude tool-call payload,
and blocking (exit 1) instead of a hint.

Self-contained: no dependency on hooks/scripts/utils.py (same reasoning as
lefthook/scripts/format_staged.py — keeps mypy/pylint single-file checks
resolvable without cross-directory sys.path tricks).
"""

from __future__ import annotations

import contextlib
import difflib
from pathlib import Path
import re
import subprocess
import sys
from typing import Any

get_parser: Any = None
with contextlib.suppress(ImportError):
    from tree_sitter_language_pack import get_parser  # type: ignore[import-not-found,no-redef]

MAX_DECLARED_LINES = 4
MARKER_RE = re.compile(
    r"^\s*(?://|#|/\*|\*)?\s*(why|hazard|invariant)\s*:", re.IGNORECASE
)
DIRECTIVE_RE = re.compile(
    r"(eslint-disable|noqa|type:\s*ignore|pragma|prettier-ignore|istanbul ignore|"
    r"pylint:\s*disable|#!)",
    re.IGNORECASE,
)
GENERATED_RE = re.compile(
    r"(@generated|do not edit|autogenerated|auto-generated|"
    r"code generated by go-bindata)",
    re.IGNORECASE,
)

_EXT_TO_TS_LANG = {
    ".py": "python",
    ".ts": "typescript",
    ".tsx": "tsx",
    ".js": "javascript",
    ".jsx": "javascript",
    ".go": "go",
}
_ts_parser_cache: dict[str, Any] = {}


def _get_ts_parser(lang: str) -> Any:  # noqa: ANN401 - tree_sitter.Parser
    """Cached tree-sitter parser for `lang`, or None if unavailable."""
    if lang in _ts_parser_cache:
        return _ts_parser_cache[lang]
    if get_parser is None:
        parser = None
    else:
        try:
            parser = get_parser(lang)
        except Exception:  # pylint: disable=broad-exception-caught
            parser = None
    _ts_parser_cache[lang] = parser
    return parser


def comment_lines(content: str, file_path: str) -> list[tuple[int, str]]:
    """Line number (1-based) + text for every comment node in the file.

    Args:
        content: full source text to scan.
        file_path: used only to resolve the tree-sitter language by extension.

    Returns:
        (line_number, comment_text) pairs, sorted ascending by line.
    """
    lang = _EXT_TO_TS_LANG.get(Path(file_path).suffix)
    if not lang or not content.strip():
        return []
    parser = _get_ts_parser(lang)
    if parser is None:
        return []
    try:
        tree = parser.parse(content.encode("utf-8", errors="ignore"))
    except Exception:  # pylint: disable=broad-exception-caught
        return []

    out: list[tuple[int, str]] = []
    stack = [tree.root_node]
    try:
        while stack:
            node = stack.pop()
            if node.type == "comment":
                text = node.text.decode("utf-8", errors="ignore")
                out.append((node.start_point[0] + 1, text))
                continue
            stack.extend(node.children)
    except Exception:  # pylint: disable=broad-exception-caught
        return []
    out.sort(key=lambda item: item[0])
    return out


def group_blocks(lines: list[tuple[int, str]]) -> list[list[tuple[int, str]]]:
    """Group consecutive comment lines into blocks.

    Args:
        lines: (line_number, text) pairs, ascending by line number.

    Returns:
        Blocks of consecutive comment lines, in encounter order.
    """
    blocks: list[list[tuple[int, str]]] = []
    for line_no, text in lines:
        if blocks and blocks[-1][-1][0] == line_no - 1:
            blocks[-1].append((line_no, text))
        else:
            blocks.append([(line_no, text)])
    return blocks


def judge_block(block: list[tuple[int, str]]) -> str | None:
    """Judge one comment block against the declared-reason policy.

    Args:
        block: consecutive (line_number, text) pairs making up one comment.

    Returns:
        A violation reason string, or None if the block is exempt or declared.
    """
    first_text = block[0][1]

    if DIRECTIVE_RE.search(first_text):
        return None
    if GENERATED_RE.search(first_text) and not MARKER_RE.search(first_text):
        return None

    if not MARKER_RE.search(first_text):
        return "undeclared comment — no why:/hazard:/invariant: marker"
    if len(block) > MAX_DECLARED_LINES:
        return f"declared comment too long ({len(block)} > {MAX_DECLARED_LINES} lines)"
    return None


def added_line_numbers(old_content: str, new_content: str) -> set[int]:
    """Line numbers (1-based, in new_content) new relative to old_content.

    Args:
        old_content: file content before the edit.
        new_content: file content after the edit.

    Returns:
        Line numbers (in new_content) touched by an insert or replace.
    """
    old_lines = old_content.splitlines()
    new_lines = new_content.splitlines()
    matcher = difflib.SequenceMatcher(a=old_lines, b=new_lines, autojunk=False)
    added: set[int] = set()
    for tag, _, _, j1, j2 in matcher.get_opcodes():
        if tag in ("insert", "replace"):
            added.update(range(j1 + 1, j2 + 1))
    return added


def find_findings(old_content: str, new_content: str, file_path: str) -> list[dict]:
    """Violations among comment blocks touched by this edit.

    Args:
        old_content: file content before the edit.
        new_content: file content after the edit.
        file_path: used to resolve the tree-sitter language by extension.

    Returns:
        One dict per violation: line, reason, snippet.
    """
    added = added_line_numbers(old_content, new_content)
    if not added:
        return []

    # why: go-bindata marks only the file header as generated, but every
    # function it emits (ModTime, Name, Size...) also gets an undeclared
    # doc-comment — exempt the whole file, not just the header's block.
    header = new_content.splitlines()[0] if new_content else ""
    if GENERATED_RE.search(header):
        return []

    blocks = group_blocks(comment_lines(new_content, file_path))
    findings: list[dict] = []
    for block in blocks:
        if not any(ln in added for ln, _ in block):
            continue
        reason = judge_block(block)
        if reason:
            start_line = block[0][0]
            snippet = block[0][1].strip()[:80]
            findings.append({"line": start_line, "reason": reason, "snippet": snippet})
    return findings


def _run(cmd: list[str], cwd: str) -> tuple[bool, str]:
    """Run `cmd`, returning (success, stdout)."""
    result = subprocess.run(  # noqa: S603 - fixed argv, no shell
        cmd, capture_output=True, text=True, cwd=cwd, check=False, timeout=30
    )
    return result.returncode == 0, result.stdout


def _staged_paths(project_root: str) -> list[str]:
    """Paths staged for commit (added/copied/modified), relative to project_root."""
    ok, output = _run(
        ["git", "diff", "--cached", "--name-only", "--diff-filter=ACM"], project_root
    )
    if not ok:
        return []
    return sorted(line.strip() for line in output.splitlines() if line.strip())


def _staged_content(project_root: str, rel_path: str) -> str:
    """Staged (index) blob content for rel_path."""
    ok, output = _run(["git", "show", f":{rel_path}"], project_root)
    return output if ok else ""


def _head_content(project_root: str, rel_path: str) -> str:
    """HEAD blob content for rel_path, or "" if the file is new."""
    ok, output = _run(["git", "show", f"HEAD:{rel_path}"], project_root)
    return output if ok else ""


def main() -> int:
    """Scan staged files for undeclared/over-long comment blocks; block on findings.

    Returns:
        1 if any violation is found, else 0.
    """
    root = str(Path.cwd())
    files = [p for p in _staged_paths(root) if Path(p).suffix in _EXT_TO_TS_LANG]

    violations: list[str] = []
    for rel_path in files:
        new_content = _staged_content(root, rel_path)
        if not new_content:
            continue
        old_content = _head_content(root, rel_path)
        violations.extend(
            f"{rel_path}:{finding['line']}: {finding['reason']} "
            f'— "{finding["snippet"]}"'
            for finding in find_findings(old_content, new_content, rel_path)
        )

    if violations:
        sys.stderr.write(
            "Comment policy violation(s) — declare why:/hazard:/invariant: or remove:\n"
        )
        for line in violations:
            sys.stderr.write(f"  {line}\n")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
